/**
 * Bakes the three OG-card faces into a committed TypeScript module.
 *
 *   pnpm gen:og-fonts
 *
 * lib/og.tsx used to `readFile` these straight out of node_modules at render
 * time, and every share card 500d the moment the site ran somewhere without a
 * filesystem (the Cloudflare Worker era; see lib/og.tsx for the history).
 * Today the cards render at build time under `output: "export"`, where a read
 * would work again — but base64 in a committed module keeps one code path that
 * cannot care where it runs, and it is why @fontsource/* are devDependencies
 * this script alone consumes.
 *
 * woff and not woff2 on purpose: satori decodes woff, and woff2 needs a
 * Brotli decompressor it does not ship. The three files are the Latin subsets
 * @fontsource already publishes, about 17 kB each, so the module costs roughly
 * 67 kB of base64 in the bundle.
 *
 * Re-run this when @fontsource/hanken-grotesk or @fontsource/ibm-plex-mono
 * changes. The output is committed; nothing generates it at build time.
 */
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const ROOT = process.cwd();
const SANS = join(ROOT, "node_modules", "@fontsource", "hanken-grotesk", "files");
const MONO = join(ROOT, "node_modules", "@fontsource", "ibm-plex-mono", "files");

const FACES = [
  ["SANS_400_B64", join(SANS, "hanken-grotesk-latin-400-normal.woff")],
  ["SANS_700_B64", join(SANS, "hanken-grotesk-latin-700-normal.woff")],
  ["MONO_400_B64", join(MONO, "ibm-plex-mono-latin-400-normal.woff")],
];

const parts = [];
let total = 0;
for (const [name, path] of FACES) {
  const buf = await readFile(path);
  total += buf.length;
  parts.push(`export const ${name} =\n  "${buf.toString("base64")}";`);
}

const out = `// Generated by scripts/gen-og-fonts.mjs. Do not edit by hand.
//
// The OG card's three faces, base64-encoded so lib/og.tsx needs no filesystem
// wherever it renders. See the script for the full reasoning.
//
// Source: @fontsource/hanken-grotesk and @fontsource/ibm-plex-mono, Latin
// subsets, woff (satori cannot decode woff2).

${parts.join("\n\n")}
`;

await writeFile(join(ROOT, "lib", "og-fonts.ts"), out);
console.log(`wrote lib/og-fonts.ts — ${FACES.length} faces, ${(total / 1024).toFixed(1)} kB raw`);
